def build_user_prompt(meta: KnowledgeMetadata) -> str:
    return f"""\
Write the complete Markdown body for the document below.

DOCUMENT TITLE: {meta.title}
DOCUMENT ID: {meta.doc_id}
VERSION: {meta.version}
LAST UPDATED: {meta.last_updated}
DEPARTMENT: {meta.department}
COMPANY: Aurora Mobile

CONTENT BRIEF:
{meta.brief}"""


def build_client(settings: Settings) -> tuple[OpenAI, str]:
    """Build the OpenRouter client and chat model from pipeline settings.

    The model comes from ``Settings.openrouter_model`` (``OPENROUTER_MODEL`` in
    the environment or ``.env``), the same value the RAG generator uses.
    """
    if not settings.openrouter_model:
        raise ValueError("OPENROUTER_MODEL is not configured")
    if not settings.openrouter_api_key:
        logger.warning("OPENROUTER_API_KEY is not set; generation requests will fail")
    client = OpenAI(
        base_url=settings.openrouter_base_url,
        api_key=settings.openrouter_api_key or None,
    )
    return client, settings.openrouter_model


def _usage(response) -> dict:
    """Normalize a chat-completion usage payload to a ``{tokens: count}`` dict."""
    usage = getattr(response, "usage", None)
    if usage is None:
        return {}
    if isinstance(usage, dict):
        return {
            key: usage[key]
            for key in ("prompt_tokens", "completion_tokens", "total_tokens")
            if usage.get(key)
        }
    return {
        key: getattr(usage, key)
        for key in ("prompt_tokens", "completion_tokens", "total_tokens")
        if getattr(usage, key, None)
    }


def _extract_text(response) -> str:
    """Return the first completion's text, or ``""`` when it is absent."""
    choices = getattr(response, "choices", None)
    if not isinstance(choices, list) or not choices:
        return ""
    message = getattr(choices[0], "message", None)
    if isinstance(message, dict):
        content = message.get("content")
    else:
        content = getattr(message, "content", None) if message is not None else None
    return content if isinstance(content, str) else ""


def _llm_generate(
    client: OpenAI,
    model: str,
    system: str,
    user: str,
    *,
    max_tokens: int | None = None,
    retries: int = 2,
) -> tuple[str, dict]:
    """Call the chat model with transient-failure retries, returning (text, usage)."""
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]
    last_exc: Exception | None = None
    for attempt in range(1, retries + 1):
        try:
            kwargs = {"max_tokens": max_tokens or BODY_MAX_TOKENS}
            response = client.chat.completions.create(model=model, messages=messages, **kwargs)
            return _extract_text(response), _usage(response)
        except Exception as exc:  # retry transient failures
            last_exc = exc
            logger.warning("LLM call failed (attempt %s/%s): %s", attempt, retries, exc)
    raise last_exc


def _parse_outline(outline_md: str) -> list[str]:
    """Extract '## ' section titles (optionally numbered) from an outline."""
    titles: list[str] = []
    for line in outline_md.splitlines():
        line = line.strip()
        m = re.search(r"#+\s+(.*?)\s*$", line)
        if not m:
            continue
        title = m.group(1).strip().strip("*").strip()
        if title and title not in titles:
            titles.append(title)
    return titles


def _generate_long_doc(
    client: OpenAI, model: str, meta: KnowledgeMetadata, target_sections: int
) -> tuple[str, dict]:
    """Generate a document section-by-section so it exceeds 10 pages."""
    outline_prompt = OUTLINE_PROMPT.format(
        target=max(11, target_sections * 3 // 4), n_sections=target_sections
    )
    outline_user = build_user_prompt(meta)
    outline_md, _ = _llm_generate(
        client, model, outline_prompt, outline_user, max_tokens=OUTLINE_MAX_TOKENS
    )
    logger.info("%s outline: %d sections", meta.doc_id, len(_parse_outline(outline_md)))

    sections = _parse_outline(outline_md)
    # Guarantee the standard opening and closing sections.
    if not sections or sections[0].lower() != "overview":
        sections.insert(0, "Overview")
    if not sections or sections[-1].lower() != "faqs":
        sections.append("FAQs")

    body_parts: list[str] = []
    total_usage: dict = {}
    generated_sections = 0

    content_sections = [s for s in sections if not s.lower().startswith("faq")]
    for start in range(0, len(content_sections), SECTION_BATCH):
        batch = content_sections[start : start + SECTION_BATCH]
        section_lines = "\n".join(f"## {s}" for s in batch)
        user = (
            f"DOCUMENT TITLE: {meta.title}\nDOCUMENT ID: {meta.doc_id}\n"
            f"VERSION: {meta.version}\nLAST UPDATED: {meta.last_updated}\n"
            f"DEPARTMENT: {meta.department}\nCOMPANY: Aurora Mobile\n\n"
            f"CONTENT BRIEF:\n{meta.brief}\n\n"
            f"WRITE THESE SECTIONS:\n{section_lines}"
        )
        part, usage = _llm_generate(
            client, model, SECTION_PROMPT, user, max_tokens=SECTION_MAX_TOKENS
        )
        part = part.strip()
        if part:
            body_parts.append(part)
            generated_sections += len(batch)
        for key in ("prompt_tokens", "completion_tokens", "total_tokens"):
            if usage.get(key):
                total_usage[key] = total_usage.get(key, 0) + usage[key]

    faq_user = (
        f"DOCUMENT TITLE: {meta.title}\nDOCUMENT ID: {meta.doc_id}\n"
        f"VERSION: {meta.version}\nDEPARTMENT: {meta.department}\n"
        f"COMPANY: Aurora Mobile\n\nCONTENT BRIEF:\n{meta.brief}"
    )
    faq, usage = _llm_generate(client, model, FAQ_PROMPT, faq_user, max_tokens=FAQ_MAX_TOKENS)
    faq = faq.strip()
    if faq:
        body_parts.append(faq)
    for key in ("prompt_tokens", "completion_tokens", "total_tokens"):
        if usage.get(key):
            total_usage[key] = total_usage.get(key, 0) + usage[key]

    logger.info(
        "%s generated in %d section call(s) (%d sections, tokens: prompt=%s "
        "completion=%s total=%s)",
        meta.doc_id,
        len(content_sections) // SECTION_BATCH + 1,
        generated_sections,
        total_usage.get("prompt_tokens"),
        total_usage.get("completion_tokens"),
        total_usage.get("total_tokens"),
    )
    return "\n\n".join(body_parts), total_usage


def generate_body(client: OpenAI, model: str, meta: KnowledgeMetadata) -> tuple[str, dict]:
    """Generate the markdown body for a document via the configured LLM."""
    if meta.sections:
        return _generate_long_doc(client, model, meta, meta.sections)

    body, usage = _llm_generate(client, model, SYSTEM_PROMPT, build_user_prompt(meta))
    logger.info(
        "%s generated (tokens: prompt=%s completion=%s total=%s)",
        meta.doc_id,
        usage.get("prompt_tokens"),
        usage.get("completion_tokens"),
        usage.get("total_tokens"),
    )
    body = body.strip()
    if not body:
        raise RuntimeError(f"LLM returned an empty body for {meta.doc_id}")
    return body, usage


