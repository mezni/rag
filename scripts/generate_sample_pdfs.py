def _parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="generate_sample_pdfs.py",
        description="Generate Aurora Mobile sample policy PDFs for the RAG "
        "pipeline using the chat model configured via .env "
        "(OPENROUTER_MODEL).",
    )
    parser.add_argument(
        "--out-dir",
        default=str(DEFAULT_OUTPUT_DIR),
        help="Output directory (default: data/raw)",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=None,
        help="Generate only the first N documents (catalog order)",
    )
    parser.add_argument(
        "--only",
        action="append",
        default=None,
        metavar="NAME",
        help="Generate only matching document(s); may repeat. Matches name "
        "substring (e.g. --only roaming).",
    )
    parser.add_argument(
        "--keep-md",
        action="store_true",
        help="Also write the raw LLM markdown body next to each PDF.",
    )
    return parser.parse_args(argv)


def _resolve_targets(args: argparse.Namespace) -> list[tuple[str, KnowledgeMetadata]]:
    names = list(KB)
    if args.only:
        names = sorted({name for name in KB if any(token in name for token in args.only)})
        if not names:
            raise SystemExit(
                f"No document matched --only {args.only}. Available: " + ", ".join(sorted(KB))
            )
    if args.limit is not None:
        names = names[: args.limit]
    return [(name, KB[name]) for name in names]


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    targets = _resolve_targets(args)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    logger.info("Initializing OpenRouter client from pipeline settings (.env) ...")
    try:
        client, model = build_client(Settings())
    except (RuntimeError, ValueError) as exc:
        logger.error("Could not start LLM client: %s", exc)
        print(
            "Set OPENROUTER_MODEL and OPENROUTER_API_KEY in your environment "
            "or .env file before running this script."
        )
        return 1

    generated, failed = 0, 0
    long_count = 0
    for name, meta in targets:
        pdf_path = out_dir / meta.category / f"{name}.pdf"
        try:
            body, usage = generate_body(client, model, meta)
        except Exception as exc:  # keep going; report at the end
            logger.error("FAILED %s: %s", meta.doc_id, exc)
            failed += 1
            continue

        if usage.get("completion_tokens") == MAX_COMPLETION_TOKENS_TO_WARN:
            logger.warning(
                "%s hit the max_tokens ceiling (%d) — output may be "
                "truncated. Re-run with --only=%s to retry.",
                meta.doc_id,
                MAX_COMPLETION_TOKENS_TO_WARN,
                name,
            )

        doc = KnowledgeDocument(metadata=meta, body_md=body)
        pages = render_pdf(doc, pdf_path)
        if args.keep_md:
            (pdf_path.with_suffix(".md")).write_text(body + "\n", encoding="utf-8")
        print(f" - {pdf_path} ({pages} pages)")
        logger.info("%s rendered: %d pages", meta.doc_id, pages)
        generated += 1
        if pages > 10:
            long_count += 1

    print(
        f"\nSuccessfully generated knowledge base PDFs under "
        f"'{out_dir.resolve()}': {generated} document(s) generated, "
        f"{failed} failed ({long_count} exceed 10 pages)."
    )
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
