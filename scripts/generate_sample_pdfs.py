def _escape_xml(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _inline(text: str) -> str:
    """Escape XML and convert markdown inline markup to ReportLab XML tags."""
    text = _escape_xml(text)
    codes: list[str] = []

    def _stash_code(m: "re.Match") -> str:
        codes.append(f'<font face="Courier" size="8.5" color="#333333">{m.group(1)}</font>')
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", _stash_code, text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<i>\1</i>", text)
    for i, c in enumerate(codes):
        text = text.replace(f"\x00{i}\x00", c)
    return text


_HEADING_RE = re.compile(r"^(#{1,6})\s+(.*)$")
_TABLE_ROW_RE = re.compile(r"^\s*\|")
_SEP_ROW_RE = re.compile(r"^\s*\|[\s:|-]+\|\s*$")
_BULLET_RE = re.compile(r"^([ \t]*)[-*+]\s+(.*)$")
_NUMBERED_RE = re.compile(r"^([ \t]*)(\d+)[.)]\s+(.*)$")
_QUOTE_RE = re.compile(r"^>\s?(.*)$")
_HR_RE = re.compile(r"^\s*(?:-{3,}|\*{3,}|_{3,})\s*$")

Block = tuple[str, str | list[list[str]] | tuple[int, str, str] | tuple[int, str]]


def _parse_markdown(body_md: str) -> list[Block]:
    """Split markdown body into (kind, payload) blocks.

    Kinds: h2 / h3 / h4 / para / bullets / numbered / table / quote / hr.
    """
    blocks: list[Block] = []
    for raw in body_md.splitlines():
        line = raw.rstrip()

        if _SEP_ROW_RE.match(line):
            continue

        head = _HEADING_RE.match(line)
        if head:
            level = len(head.group(1))
            kind = {2: "h2", 3: "h3", 4: "h4"}.get(level, "h2")
            blocks.append((kind, head.group(2).strip()))
            continue

        if _HR_RE.match(line):
            blocks.append(("hr", ""))
            continue

        match = _QUOTE_RE.match(line)
        if match:
            blocks.append(("quote", match.group(1).strip()))
            continue

        if _TABLE_ROW_RE.match(line):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if blocks and blocks[-1][0] == "table":
                blocks[-1][1].append(cells)  # type: ignore[arg-type]
            else:
                blocks.append(("table", [cells]))
            continue

        match = _NUMBERED_RE.match(line)
        if match:
            indent = len(match.group(1))
            blocks.append(("numbered", (indent, match.group(2), match.group(3).strip())))
            continue

        match = _BULLET_RE.match(line)
        if match:
            indent = len(match.group(1))
            blocks.append(("bullets", (indent, match.group(2).strip())))
            continue

        if not line.strip():
            continue

        blocks.append(("para", line.strip()))

    return blocks


