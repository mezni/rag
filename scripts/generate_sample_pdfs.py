def _pdf_page_count(path: Path) -> int:
    """Count pages in a rendered PDF by scanning its page objects."""
    data = path.read_bytes()
    return data.count(b"/Type /Page") - data.count(b"/Type /Pages")


def render_pdf(doc: KnowledgeDocument, out_path: Path) -> int:
    """Render one knowledge document to a branded Aurora Mobile PDF.

    Returns the number of pages in the rendered PDF.
    """
    meta = doc.metadata
    styles = _build_styles()

    def on_page(canvas, _doc) -> None:
        canvas.saveState()
        width, height = _doc.pagesize

        # Header band
        canvas.setFillColor(NAVY)
        canvas.setFont("Helvetica-Bold", 8)
        canvas.drawString(MARGIN, height - 0.55 * inch, "AURORA MOBILE")
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 8)
        canvas.drawRightString(
            width - MARGIN,
            height - 0.55 * inch,
            f"{meta.doc_id}  \u00b7  v{meta.version}  \u00b7  {meta.title}",
        )
        canvas.setStrokeColor(BORDER)
        canvas.setLineWidth(0.7)
        canvas.line(MARGIN, height - 0.62 * inch, width - MARGIN, height - 0.62 * inch)

        # Footer band
        canvas.line(MARGIN, 0.5 * inch, width - MARGIN, 0.5 * inch)
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(
            MARGIN,
            0.38 * inch,
            "Confidential \u2014 for internal training and reference only. \u00a9 2026 Aurora Mobile.",
        )
        canvas.drawRightString(
            width - MARGIN,
            0.38 * inch,
            f"Page {canvas.getPageNumber()}",
        )
        canvas.restoreState()

    story: list = []
    story.append(Spacer(1, 6))
    story.append(Paragraph("AURORA MOBILE  \u00b7  KNOWLEDGE BASE", styles["kicker"]))
    story.append(Paragraph(meta.title, styles["title"]))
    story.append(
        Paragraph(
            "Category B \u2014 Policy &amp; Process Knowledge Base",
            styles["subtitle"],
        )
    )
    story.append(_make_info_table(meta, styles))
    story.append(
        HRFlowable(
            width="100%",
            thickness=1.1,
            color=NAVY,
            spaceBefore=10,
            spaceAfter=2,
        )
    )
    story.extend(_body_to_flowables(doc.body_md, styles, AVAILABLE_WIDTH))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    document = SimpleDocTemplate(
        str(out_path),
        pagesize=letter,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
        topMargin=0.85 * inch,
        bottomMargin=0.75 * inch,
        title=f"{meta.title} \u2014 {meta.doc_id}",
        author="Aurora Mobile",
        subject="Category B knowledge base document",
    )
    document.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return _pdf_page_count(out_path)


