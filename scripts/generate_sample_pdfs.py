def _build_table(cells: list[list[str]], width: float, styles: dict) -> Table:
    styled = []
    for r, row in enumerate(cells):
        styled_row = []
        for cell in row:
            text = _inline(cell)
            style = styles["table_head"] if r == 0 else styles["table_cell"]
            styled_row.append(Paragraph(text, style))
        styled.append(styled_row)

    n_cols = max(len(r) for r in styled)
    col_width = width / max(n_cols, 1)
    col_widths = [col_width] * n_cols

    t = Table(styled, colWidths=col_widths, repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT]),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 3.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ]
        )
    )
    return t


def _body_to_flowables(body_md: str, styles: dict, width: float) -> list:
    flowables: list = []
    in_bullet_group = False
    in_number_group = False

    def _end_group() -> None:
        nonlocal in_bullet_group, in_number_group
        if in_bullet_group or in_number_group:
            flowables.append(Spacer(1, 4))
            in_bullet_group = False
            in_number_group = False

    for kind, payload in _parse_markdown(body_md):
        if kind in ("h2", "h3", "h4", "hr"):
            _end_group()
            if kind == "hr":
                flowables.append(
                    HRFlowable(
                        width="100%",
                        thickness=0.8,
                        color=BORDER,
                        spaceBefore=2,
                        spaceAfter=8,
                    )
                )
            else:
                flowables.append(Paragraph(_inline(payload), styles[kind]))
            continue

        if kind == "quote":
            _end_group()
            flowables.append(Paragraph(_inline(payload), styles["quote"]))
            continue

        if kind == "table":
            _end_group()
            flowables.append(_build_table(payload, width, styles))
            flowables.append(Spacer(1, 6))
            continue

        if kind == "bullets":
            indent, text = payload
            if not in_bullet_group:
                flowables.append(Spacer(1, 2))
                in_bullet_group = True
            indent_px = 9 * (indent // 2)
            style = ParagraphStyle(
                "bullet_lvl",
                parent=styles["bullet"],
                leftIndent=16 + indent_px,
                firstLineIndent=-9,
            )
            flowables.append(Paragraph(_inline(text), style, bulletText="\u2022"))
            continue

        if kind == "numbered":
            indent, num, text = payload
            if not in_number_group:
                flowables.append(Spacer(1, 2))
                in_number_group = True
            indent_px = 9 * (indent // 2)
            style = ParagraphStyle(
                "number_lvl",
                parent=styles["number"],
                leftIndent=18 + indent_px,
                firstLineIndent=-10,
            )
            flowables.append(Paragraph(_inline(text), style, bulletText=f"{num}."))
            continue

        # paragraph
        _end_group()
        if payload.startswith("**Q:"):
            flowables.append(Paragraph(_inline(payload), styles["fq"]))
        elif payload.startswith("**A:"):
            flowables.append(Paragraph(_inline(payload), styles["fa"]))
        else:
            flowables.append(Paragraph(_inline(payload), styles["body"]))

    _end_group()
    return flowables


